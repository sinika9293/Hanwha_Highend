from __future__ import annotations


def _lifestyle_item_schema() -> dict:
    return {
        "type": "object",
        "required": ["title", "summary", "source", "date"],
        "properties": {
            "title": {"type": "string", "description": "1~2줄로 요약 가능한 제목"},
            "summary": {"type": "string"},
            "source": {"type": "string", "description": "매체명"},
            "source_url": {
                "type": "string",
                "description": "이 항목의 근거가 된 원문 기사 URL. 확인 못 하면 빈 문자열.",
            },
            "date": {"type": "string"},
        },
    }


def _lifestyle_category_schema() -> dict:
    return {
        "type": "object",
        "required": ["range_label", "domestic", "global"],
        "properties": {
            "range_label": {"type": "string"},
            "domestic": {
                "type": "array",
                "items": _lifestyle_item_schema(),
                "minItems": 2,
            },
            "global": {
                "type": "array",
                "items": _lifestyle_item_schema(),
                "minItems": 2,
            },
        },
    }


